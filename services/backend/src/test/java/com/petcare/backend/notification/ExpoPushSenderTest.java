package com.petcare.backend.notification;

import java.time.OffsetDateTime;
import java.time.ZoneOffset;
import java.util.List;

import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.core.io.ClassPathResource;
import org.springframework.http.MediaType;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.embedded.EmbeddedDatabase;
import org.springframework.jdbc.datasource.embedded.EmbeddedDatabaseBuilder;
import org.springframework.jdbc.datasource.embedded.EmbeddedDatabaseType;
import org.springframework.jdbc.datasource.init.ResourceDatabasePopulator;
import org.springframework.test.json.JsonCompareMode;
import org.springframework.test.web.client.MockRestServiceServer;
import org.springframework.web.client.RestClient;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;
import static org.springframework.test.web.client.match.MockRestRequestMatchers.content;
import static org.springframework.test.web.client.match.MockRestRequestMatchers.requestTo;
import static org.springframework.test.web.client.response.MockRestResponseCreators.withSuccess;

class ExpoPushSenderTest {

    private static final String SEND = "https://example.test/send";
    private static final String RECEIPTS = "https://example.test/receipts";
    private static final String ACTIVE = "ExpoPushToken[active]";
    private static final String INVALID = "ExponentPushToken[invalid]";

    private EmbeddedDatabase database;
    private JdbcTemplate jdbc;
    private MockRestServiceServer http;
    private ExpoPushSender sender;

    @BeforeEach
    void setUp() {
        database = new EmbeddedDatabaseBuilder().setType(EmbeddedDatabaseType.H2)
                .generateUniqueName(true).build();
        jdbc = new JdbcTemplate(database);
        jdbc.execute("""
                CREATE TABLE user_devices (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    token VARCHAR(512) NOT NULL,
                    push_enabled BOOLEAN DEFAULT TRUE,
                    last_seen_at TIMESTAMP WITH TIME ZONE NOT NULL
                )
                """);
        new ResourceDatabasePopulator(new ClassPathResource(
                "db/migration/V22__expo_device_ownership_and_receipts.sql")).execute(database);
        RestClient.Builder builder = RestClient.builder();
        http = MockRestServiceServer.bindTo(builder).build();
        sender = new ExpoPushSender(SEND, RECEIPTS, jdbc, builder.build());
    }

    @AfterEach
    void tearDown() {
        database.shutdown();
    }

    @Test
    void sendsOnlyNeutralMessageAndRouteAndDisablesUnregisteredDevice() {
        register(INVALID, OffsetDateTime.now(ZoneOffset.UTC).minusMinutes(1));
        http.expect(requestTo(SEND)).andExpect(content().json("""
                [
                    {"to":"ExpoPushToken[active]", "title":"Pet Care",
                     "body":"Откройте приложение, чтобы посмотреть напоминание.",
                     "channelId":"reminders","data":{"route":"tasks","careTaskId":42}},
                    {"to":"ExponentPushToken[invalid]", "title":"Pet Care",
                     "body":"Откройте приложение, чтобы посмотреть напоминание.",
                     "channelId":"reminders","data":{"route":"tasks","careTaskId":42}}
                ]
                """, JsonCompareMode.STRICT))
                .andRespond(withSuccess("""
                        {"data":[{"status":"ok","id":"receipt-1"},
                        {"status":"error","details":{"error":"DeviceNotRegistered"}}]}
                        """, MediaType.APPLICATION_JSON));

        assertEquals(List.of(INVALID), sender.send(List.of(ACTIVE, INVALID), "private title",
                "private details", "{\"careTaskId\":42,\"petName\":\"private name\"}"));
        assertEquals(ACTIVE, jdbc.queryForObject(
                "SELECT token FROM expo_push_receipts WHERE id = 'receipt-1'", String.class));
        assertFalse(isEnabled(INVALID));
        http.verify();
    }

    @Test
    void delayedPermanentFailureDoesNotDisableNewRegistration() {
        OffsetDateTime sentAt = OffsetDateTime.now(ZoneOffset.UTC).minusMinutes(20);
        register(INVALID, sentAt.minusMinutes(1));
        register(ACTIVE, sentAt.plusMinutes(1));
        jdbc.update("INSERT INTO expo_push_receipts (id, token, sent_at) VALUES (?, ?, ?)",
                "receipt-2", INVALID, sentAt);
        jdbc.update("INSERT INTO expo_push_receipts (id, token, sent_at) VALUES (?, ?, ?)",
                "receipt-3", ACTIVE, sentAt.plusSeconds(1));
        http.expect(requestTo(RECEIPTS)).andExpect(content().json("{\"ids\":[\"receipt-2\",\"receipt-3\"]}"))
                .andRespond(withSuccess("""
                        {"data":{
                          "receipt-2":{"status":"error","details":{"error":"DeviceNotRegistered"}},
                          "receipt-3":{"status":"error","details":{"error":"DeviceNotRegistered"}}
                        }}
                        """, MediaType.APPLICATION_JSON));

        sender.checkReceipts();

        assertFalse(isEnabled(INVALID));
        assertTrue(isEnabled(ACTIVE));
        assertEquals(0, jdbc.queryForObject("SELECT COUNT(*) FROM expo_push_receipts", Integer.class));
        http.verify();
    }

    private void register(String token, OffsetDateTime lastSeen) {
        jdbc.update("INSERT INTO user_devices (token, last_seen_at) VALUES (?, ?)", token, lastSeen);
    }

    private boolean isEnabled(String token) {
        return jdbc.queryForObject("SELECT push_enabled FROM user_devices WHERE token = ?", Boolean.class, token);
    }
}
